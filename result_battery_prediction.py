def plot_prediction_curves(pred, true, metrics, output_folder):
    setup_style()
    fig = plt.figure(figsize=(6.8, 4.2))
    gs = fig.add_gridspec(2, 2, hspace=0.35, wspace=0.30)

    # Full trajectory
    ax1 = fig.add_subplot(gs[0, :])
    ax1.plot(true, color=COLORS['true'], linewidth=PLOT_CONFIG['line_width_true'], alpha=PLOT_CONFIG['alpha_true'], label='True')
    ax1.plot(pred, color=COLORS['predicted'], linewidth=PLOT_CONFIG['line_width_pred'], alpha=PLOT_CONFIG['alpha_pred'], label='Predicted')
    ax1.set_xlabel('Sample Index'); ax1.set_ylabel('SOH')
    ax1.set_title('SOH Prediction: Full Trajectory')
    apply_axes_style(ax1); ax1.legend(frameon=False)

    # Error distribution
    ax2 = fig.add_subplot(gs[1, 0])
    error = pred - true
    ax2.hist(error, bins=40, color=COLORS['hist'], alpha=0.85)
    ax2.axvline(np.mean(error), color=COLORS['error'], linestyle='-', linewidth=1.5, label=f'Mean: {np.mean(error):.4f}')
    ax2.axvline(0, color='#666666', linestyle='-', linewidth=1.0, alpha=0.6)
    ax2.set_xlabel('Prediction Error (Pred - True)'); ax2.set_ylabel('Count')
    ax2.set_title('Error Distribution')
    apply_axes_style(ax2); ax2.legend(frameon=False)

    # Scatter Pred vs True
    ax3 = fig.add_subplot(gs[1, 1])
    ax3.scatter(true, pred, s=8, alpha=0.45, color=COLORS['predicted'])
    min_val = min(true.min(), pred.min()); max_val = max(true.max(), pred.max())
    ax3.plot([min_val, max_val], [min_val, max_val], color='#444444', linestyle='-', linewidth=1.2)
    ax3.set_xlabel('True SOH'); ax3.set_ylabel('Predicted SOH')
    ax3.set_title('Predicted vs. True')
    apply_axes_style(ax3); ax3.set_aspect('equal', adjustable='box')

    # Metrics textbox
    metrics_text = f"MAE: {metrics['MAE']:.4f} | RMSE: {metrics['RMSE']:.4f} | MAPE: {metrics['MAPE']:.2f}% | R²: {metrics['R²']:.4f}"
    fig.text(0.02, 0.02, metrics_text, fontsize=PLOT_CONFIG['font_size'],
             bbox=dict(boxstyle='round', facecolor='white', alpha=0.9, edgecolor='#A0A0A0'), family='monospace')

    os.makedirs(output_folder, exist_ok=True)
    for ext in ('png', 'pdf'):
        out_path = os.path.join(output_folder, f'soh_prediction_analysis.{ext}')
        fig.savefig(out_path, dpi=PLOT_CONFIG['dpi'], bbox_inches='tight', facecolor='white')
    plt.close(fig)
    print(f"✓ 已保存整体图到: {output_folder}/soh_prediction_analysis.(png|pdf)")


essential_titles = False  # set True if you prefer no per-figure titles

def plot_per_battery(pred, true, result_folder, data_root=DATA_ROOT, output_subdir='per_battery'):
    setup_style()
    # 1) Test list: logging.txt -> fallback main rule
    try:
        candidates = _collect_candidate_logs(result_folder)
        test_paths = extract_last_path_list_from_log(candidates)
        print(f"✓ 从日志解析到 {len(test_paths)} 个测试电池路径")
    except Exception as e:
        print(f"[提示] 无法从日志解析，回退主规则: {e}")
        test_paths = reconstruct_test_paths_by_main_rule(data_root)
        print(f"✓ 主规则重建 {len(test_paths)} 个测试电池路径")

    # 2) Segment lengths by the same cleaning pipeline
    lengths = compute_test_segment_lengths(test_paths)
    total_len = sum(lengths)
    if total_len != len(pred):
        print(f"[警告] 分段总长度({total_len})≠预测长度({len(pred)}). 将按最小长度裁剪继续。")
        min_len = min(total_len, len(pred))
        acc = 0; adj = []
        for L in lengths:
            if acc + L <= min_len:
                adj.append(L); acc += L
            else:
                adj.append(max(min_len - acc, 0)); acc = min_len; break
        lengths = adj

    out_dir = os.path.join(result_folder, output_subdir)
    os.makedirs(out_dir, exist_ok=True)

    # 3) Plot per battery
    start = 0
    for i, (csv_path, seg_len) in enumerate(zip(test_paths, lengths), start=1):
        if seg_len <= 0:
            continue
        end = start + seg_len
        p = pred[start:end]; t = true[start:end]
        start = end

        fig, ax = plt.subplots(figsize=PLOT_CONFIG['figure_size'])
        ax.plot(t, color=COLORS['true'], linewidth=PLOT_CONFIG['line_width_true'], alpha=PLOT_CONFIG['alpha_true'], label='True')
        ax.plot(p, color=COLORS['predicted'], linewidth=PLOT_CONFIG['line_width_pred'], alpha=PLOT_CONFIG['alpha_pred'], label='Predicted')
        ax.set_xlabel('Sample Index (battery)'); ax.set_ylabel('SOH')
        apply_axes_style(ax)
        ax.legend(frameon=False, loc='best')

        name = Path(csv_path).stem
        if essential_titles:
            ax.set_title('')
        else:
            m = calculate_metrics(p, t)
            ax.set_title(f'{name}   MSE:{np.mean((p-t)**2):.4f}  MAE:{m["MAE"]:.4f}  R²:{m["R²"]:.3f}')

        for ext in ('png', 'pdf'):
            out_path = os.path.join(out_dir, f"battery_{i:02d}_{name}.{ext}")
            fig.savefig(out_path, dpi=PLOT_CONFIG['dpi'], bbox_inches='tight', facecolor='white')
        plt.close(fig)
        print(f"✓ 已保存: {out_dir}/battery_{i:02d}_{name}.(png|pdf)")

