def _three_sigma_indices(series: pd.Series):
    mu = series.mean(); sigma = series.std()
    return np.arange(series.shape[0])[((mu - 3 * sigma > series) | (mu + 3 * sigma < series)).to_numpy()]


def _delete_3_sigma(df: pd.DataFrame) -> pd.DataFrame:
    df = df.replace([np.inf, -np.inf], np.nan)
    df = df.dropna().reset_index(drop=True)
    out_index = []
    for col in df.columns:
        out_index.extend(_three_sigma_indices(df[col]))
    out_index = list(set(out_index))
    df = df.drop(out_index, axis=0).reset_index(drop=True)
    return df


def compute_test_segment_lengths(test_csv_paths):
    lengths = []
    for p in test_csv_paths:
        df = pd.read_csv(p)
        df.insert(df.shape[1]-1, 'cycle index', np.arange(df.shape[0]))
        df = _delete_3_sigma(df)
        seg_len = max(len(df) - 1, 0)
        lengths.append(seg_len)
    return lengths

