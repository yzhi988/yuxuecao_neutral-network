def apply_axes_style(ax):
    """Minimalist axes: remove top/right spines, inward ticks, subtle grid."""
    ax.spines['top'].set_visible(False)
    ax.spines['right'].set_visible(False)
    ax.tick_params(direction='in', length=4, width=0.8, colors='#1A1A1A')
    ax.grid(True, alpha=PLOT_CONFIG['grid_alpha'])


def load_data(result_folder):
    pred_path = os.path.join(result_folder, 'pred_label.npy')
    true_path = os.path.join(result_folder, 'true_label.npy')
    if not os.path.exists(pred_path):
        raise FileNotFoundError(f"预测数据文件不存在: {pred_path}")
    if not os.path.exists(true_path):
        raise FileNotFoundError(f"真实数据文件不存在: {true_path}")
    pred = np.load(pred_path).flatten()
    true = np.load(true_path).flatten()
    if pred.shape != true.shape:
        raise ValueError(f"数据形状不匹配: pred {pred.shape} vs true {true.shape}")
    return pred, true


def calculate_metrics(pred, true):
    eps = 1e-8
    mae = np.mean(np.abs(pred - true))
    rmse = np.sqrt(np.mean((pred - true) ** 2))
    mape = np.mean(np.abs((pred - true) / (true + eps))) * 100
    ss_res = np.sum((pred - true) ** 2)
    ss_tot = np.sum((true - np.mean(true)) ** 2) + eps
    r2 = 1 - (ss_res / ss_tot)
    return {'MAE': mae, 'RMSE': rmse, 'MAPE': mape, 'R²': r2}

