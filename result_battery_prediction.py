def _collect_candidate_logs(result_folder: str):
    cands = [
        os.path.join(result_folder, 'logging.txt'),
        os.path.join(os.path.dirname(result_folder.rstrip('/')), 'logging.txt'),
        os.path.join(os.path.dirname(os.path.dirname(result_folder.rstrip('/'))), 'logging.txt'),
    ]
    uniq = []
    for p in cands:
        if p not in uniq and os.path.exists(p):
            uniq.append(p)
    return uniq


def extract_last_path_list_from_log(log_files):
    if isinstance(log_files, (str, os.PathLike)):
        log_files = [str(log_files)]
    path_lists = []
    for log_file in log_files:
        try:
            with open(log_file, 'r', encoding='utf-8', errors='ignore') as f:
                lines = f.readlines()
        except Exception:
            continue
        for i, line in enumerate(lines):
            if 'data path' in line.lower():
                if i + 1 < len(lines):
                    raw_next = lines[i + 1].strip()
                    if raw_next.startswith('[') and raw_next.endswith(']'):
                        try:
                            lst = ast.literal_eval(raw_next)
                            if isinstance(lst, list):
                                path_lists.append(lst)
                                continue
                        except Exception:
                            pass
                # fallback: try to assemble a [...] snippet
                buf = ''
                start_idx = line.find('[')
                j = i
                if start_idx >= 0:
                    buf += line[start_idx:]
                else:
                    j = i + 1
                while j + 1 < len(lines) and ']' not in buf:
                    j += 1
                    buf += lines[j]
                buf = buf.strip()
                lpos = buf.find('['); rpos = buf.find(']')
                if lpos >= 0 and rpos > lpos:
                    snippet = buf[lpos:rpos+1]
                    try:
                        lst = ast.literal_eval(snippet)
                        if isinstance(lst, list):
                            path_lists.append(lst)
                    except Exception:
                        pass
    if not path_lists:
        raise RuntimeError("日志中未解析到 data path 列表")
    return path_lists[-1]


def reconstruct_test_paths_by_main_rule(data_root: str):
    test_list = []
    for batch in BATCH_NAMES:
        batch_root = os.path.join(data_root, batch)
        if not os.path.isdir(batch_root):
            continue
        files = os.listdir(batch_root)
        for f in files:
            try:
                battery_id = int(f.split('-')[-1].split('.')[0])
            except Exception:
                continue
            if battery_id % 5 == 0:
                test_list.append(os.path.join(batch_root, f))
    # Sort for determinism (may differ from runtime os.listdir order)
    test_list = sorted(test_list)
    if not test_list:
        raise RuntimeError(f"在 {data_root} 下未找到测试集 CSV。")
    return test_list

